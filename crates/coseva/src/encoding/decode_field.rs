    #[derive(Debug, Default, Eq, PartialEq)]
    struct AlwaysInvalid;

    impl<'record> DecodeField<'record> for AlwaysInvalid {
        fn decode_field(
            _bytes: Option<&'record [u8]>,
            index: usize,
            name: &'static str,
        ) -> Result<Self, Error> {
            Err(Error::field(ErrorKind::InvalidValue, index, Some(name)))
        }
    }

    fn assert_field_error(error: &Error, index: usize, name: &'static str) {
        assert_eq!(error.location().field, index);
        assert_eq!(error.field_name(), Some(name));
    }

    struct NullAwareEmpty;

    impl<'record> DecodeRecord<'record> for NullAwareEmpty {
        fn get_field(&self, index: usize) -> Option<&'record [u8]> {
            (index == 0).then_some(b"")
        }

        fn is_null_aware(&self) -> bool {
            true
        }
    }

    #[test]
    fn test_decode_field_into_from_record() {
        let mut direct = b"stale".to_vec();
        direct
            .decode_field_into(Some(b"fresh"), 0, "bytes_field")
            .expect("decodes bytes directly");
        assert_eq!(direct, b"fresh");

        let mut rec = ByteRecord::new();
        rec.push_field(b"bytes_field");
        rec.push_field(b"str_field");
        rec.push_field(b"123");

        let r = ByteRecordRef::new(&rec);

        let mut v = b"stale".to_vec();
        v.decode_field_into_from_record(&r, 0, "bytes_field")
            .expect("decodes bytes");
        assert_eq!(v, b"bytes_field");

        let mut s = String::new();
        s.decode_field_into_from_record(&r, 1, "str_field")
            .expect("decodes str");
        assert_eq!(s, "str_field");

        let custom =
            CustomField::decode_field_from_record(&r, 2, "custom").expect("decodes custom");
        assert_eq!(custom.0, 123);

        let mut custom_target = CustomField(0);
        custom_target
            .decode_field_into(Some(b"456"), 2, "custom")
            .expect("decodes into custom");
        assert_eq!(custom_target.0, 456);

        custom_target
            .decode_field_into_from_record(&r, 2, "custom")
            .expect("decodes into custom from record");
        assert_eq!(custom_target.0, 123);

        // Error branches for default decode_field_into and decode_field_into_from_record
        assert!(
            custom_target
                .decode_field_into(Some(b"not_a_number"), 2, "custom")
                .is_err()
        );
        let mut bad_rec = ByteRecord::new();
        bad_rec.push_field(b"not_a_number");
        let bad_r = ByteRecordRef::new(&bad_rec);
        assert!(
            custom_target
                .decode_field_into_from_record(&bad_r, 0, "custom")
                .is_err()
        );

        let mut s_err = String::new();
        assert!(
            s_err
                .decode_field_into(Some(b"\xff\xff"), 0, "bad")
                .is_err()
        );
    }

