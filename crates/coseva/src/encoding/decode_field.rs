/// Decode a single CSV field value from raw bytes.
///
/// The `'record` lifetime allows implementations to borrow directly from the
/// source record without copying. Owned types ignore it.
///
/// This trait is called by [`CsvDecode`](super::CsvDecode) impls generated by the derive macro
/// and can be implemented for custom field types.
/// For a worked example, see [`super::CsvDecode`].
pub trait DecodeField<'record>: Sized {
    /// Parse `bytes` into `Self`.
    ///
    /// `bytes` is `None` when the CSV field is absent (the record is shorter
    /// than expected). Most implementations treat `None` and `Some(b"")`
    /// equivalently; [`Option<T>`] treats both as `None`.
    ///
    /// `index` and `name` are used to construct an [`Error`](crate::Error) on failure.
    ///
    /// # Errors
    ///
    /// Returns an [`Error`](crate::Error) when the bytes cannot be converted to `Self`.
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error>;

    /// Decode field `index` directly from a record, with awareness of
    /// explicit NULL metadata.
    ///
    /// The default implementation ignores NULL-awareness entirely and
    /// simply forwards to [`Self::decode_field`] with `record.get_field(index)`,
    /// so every existing `DecodeField` implementation keeps its current
    /// behavior unchanged. [`Option<T>`] overrides this method: on a
    /// NULL-aware record, an explicit NULL or a missing field decodes to
    /// `None`, while a present (even empty) field decodes to
    /// `Some(T::decode_field(..))` — preserving `Some(<empty>)` for
    /// `Option<String>`/`Option<Vec<u8>>` and the underlying type's parse
    /// error for `Option<numeric>`. On a non-NULL-aware record, `Option<T>`
    /// treats both absent and present-empty fields as `None`.
    ///
    /// Generated `#[derive(CsvDecode)]` code calls this method instead of
    /// [`Self::decode_field`] directly.
    ///
    /// # Errors
    ///
    /// Returns an [`Error`](crate::Error) under the same conditions as
    /// [`Self::decode_field`].
    fn decode_field_from_record<R>(
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        Self::decode_field(record.get_field(index), index, name)
    }

    /// Parse `bytes` into an existing value, reusing its allocations.
    ///
    /// The default implementation is equivalent to
    /// `*self = Self::decode_field(bytes, index, name)?`. [`String`] and
    /// [`Vec<u8>`] override it to overwrite their existing buffer instead of
    /// allocating a new one.
    ///
    /// # Errors
    ///
    /// Returns an [`Error`](crate::Error) under the same conditions as
    /// [`Self::decode_field`]. On failure `self` is left in an unspecified
    /// but valid state.
    fn decode_field_into(
        &mut self,
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error> {
        *self = Self::decode_field(bytes, index, name)?;
        Ok(())
    }

    /// Decode field `index` directly from a record into an existing value,
    /// reusing its allocations.
    ///
    /// The default implementation is equivalent to
    /// `*self = Self::decode_field_from_record(record, index, name)?`, so
    /// every existing implementation keeps its current behavior. Generated
    /// `#[derive(CsvDecode)]` code calls this method from `csv_decode_into`.
    ///
    /// # Errors
    ///
    /// Returns an [`Error`](crate::Error) under the same conditions as
    /// [`Self::decode_field_from_record`]. On failure `self` is left in an
    /// unspecified but valid state.
    fn decode_field_into_from_record<R>(
        &mut self,
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        *self = Self::decode_field_from_record(record, index, name)?;
        Ok(())
    }
}

// &'record [u8] — zero-copy borrow

impl<'record> DecodeField<'record> for &'record [u8] {
    #[inline]
    fn decode_field(
        bytes: Option<&'record [u8]>,
        _index: usize,
        _name: &'static str,
    ) -> Result<Self, Error> {
        Ok(bytes.unwrap_or(b""))
    }
}

// &'record str — zero-copy borrow with UTF-8 validation

/// Build the error for a field that was not valid UTF-8.
///
/// Outlined and cold: inlining `Error` construction made `decode_field` look
/// expensive to LLVM and blocked inlining it into generated decoding bodies,
/// costing 37 instructions per field as an out-of-line call.
#[cold]
#[inline(never)]
fn field_error(kind: ErrorKind, index: usize, name: &'static str) -> Error {
    Error::field(kind, index, Some(name))
}

#[cold]
#[inline(never)]
fn invalid_utf8(error: str::Utf8Error, index: usize, name: &'static str) -> Error {
    Error::field(ErrorKind::InvalidUtf8(error), index, Some(name))
}

// CSV fields are overwhelmingly short and ASCII; screening for ASCII first with
// a word-at-a-time scan avoids the general validator's alignment and
// multi-byte machinery.
#[inline]
fn borrow_utf8(bytes: &[u8]) -> Result<&str, str::Utf8Error> {
    coseva_unsafe::bytes::borrow_utf8(bytes)
}

impl<'record> DecodeField<'record> for &'record str {
    #[inline]
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error> {
        let bytes = bytes.unwrap_or(b"");
        borrow_utf8(bytes).map_err(|e| invalid_utf8(e, index, name))
    }
}

// Vec<u8> — owned copy

fn overwrite_bytes(target: &mut Vec<u8>, bytes: &[u8]) {
    target.clear();
    target.extend_from_slice(bytes);
}

impl<'record> DecodeField<'record> for Vec<u8> {
    fn decode_field(
        bytes: Option<&'record [u8]>,
        _index: usize,
        _name: &'static str,
    ) -> Result<Self, Error> {
        Ok(bytes.unwrap_or(b"").to_vec())
    }

    fn decode_field_into(
        &mut self,
        bytes: Option<&'record [u8]>,
        _index: usize,
        _name: &'static str,
    ) -> Result<(), Error> {
        overwrite_bytes(self, bytes.unwrap_or(b""));
        Ok(())
    }

    fn decode_field_into_from_record<R>(
        &mut self,
        record: &R,
        index: usize,
        _name: &'static str,
    ) -> Result<(), Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        overwrite_bytes(self, record.get_field(index).unwrap_or_default());
        Ok(())
    }
}

// String — owned UTF-8

impl<'record> DecodeField<'record> for String {
    #[inline]
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error> {
        let bytes = bytes.unwrap_or(b"");
        borrow_utf8(bytes)
            .map(str::to_owned)
            .map_err(|e| invalid_utf8(e, index, name))
    }

    #[inline]
    fn decode_field_into(
        &mut self,
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error> {
        let text = borrow_utf8(bytes.unwrap_or(b"")).map_err(|e| invalid_utf8(e, index, name))?;
        self.clear();
        self.push_str(text);
        Ok(())
    }

    fn decode_field_into_from_record<R>(
        &mut self,
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        self.decode_field_into(record.get_field(index), index, name)
    }
}

// CompactString — owned UTF-8, stored inline when short

/// Decodes exactly like [`String`], but a field of 24 bytes or fewer is held
/// inline and allocates nothing.
///
/// CSV fields are very often that short — state codes, currencies, enum-like
/// flags, city names, formatted numbers — so this is the cheaper owned string
/// for most columns, while being no larger than a [`String`].
#[cfg(feature = "compact_str")]
impl<'record> DecodeField<'record> for CompactString {
    #[inline]
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error> {
        let bytes = bytes.unwrap_or(b"");
        borrow_utf8(bytes)
            .map(Self::from)
            .map_err(|e| invalid_utf8(e, index, name))
    }

    #[inline]
    fn decode_field_into(
        &mut self,
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error> {
        let text = borrow_utf8(bytes.unwrap_or(b"")).map_err(|e| invalid_utf8(e, index, name))?;
        self.clear();
        self.push_str(text);
        Ok(())
    }

    fn decode_field_into_from_record<R>(
        &mut self,
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        self.decode_field_into(record.get_field(index), index, name)
    }
}

// bool — byte-native "true"/"false" and "1"/"0"

impl<'record> DecodeField<'record> for bool {
    #[inline]
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error> {
        match bytes.unwrap_or(b"") {
            b"true" | b"1" => Ok(true),
            b"false" | b"0" => Ok(false),
            _ => Err(field_error(ErrorKind::InvalidValue, index, name)),
        }
    }
}

macro_rules! impl_decode_field_integer {
    ($(($ty:ty, $parse:ident)),+ $(,)?) => {
        $(
            impl<'record> DecodeField<'record> for $ty {
                #[inline]
                fn decode_field(
                    bytes: Option<&'record [u8]>,
                    index: usize,
                    name: &'static str,
                ) -> Result<Self, Error> {
                    let bytes = bytes.unwrap_or(b"");
                    $parse(bytes).map_err(|kind| field_error(kind, index, name))
                }
            }
        )+
    };
}

impl_decode_field_integer!(
    (i8, parse_i8),
    (i16, parse_i16),
    (i32, parse_i32),
    (i64, parse_i64),
    (i128, parse_i128),
    (isize, parse_isize),
    (u8, parse_u8),
    (u16, parse_u16),
    (u32, parse_u32),
    (u64, parse_u64),
    (u128, parse_u128),
    (usize, parse_usize),
);

/// Floats parse straight from raw bytes; an empty field is reported as
/// [`ErrorKind::EmptyField`] and any other rejection as
/// [`ErrorKind::InvalidValue`], matching the [`crate::FromBytes`] impls.
macro_rules! impl_decode_field_float {
    ($($ty:ty),+ $(,)?) => {
        $(
            impl<'record> DecodeField<'record> for $ty {
                #[inline]
                fn decode_field(
                    bytes: Option<&'record [u8]>,
                    index: usize,
                    name: &'static str,
                ) -> Result<Self, Error> {
                    let bytes = bytes.unwrap_or(b"");
                    fast_float2::parse(bytes).map_err(|_error| {
                        let kind = if bytes.is_empty() {
                            ErrorKind::EmptyField
                        } else {
                            ErrorKind::InvalidValue
                        };
                        Error::field(kind, index, Some(name))
                    })
                }
            }
        )+
    };
}

impl_decode_field_float!(f32, f64);

// Option<T> — None for absent or empty fields

impl<'record, T: DecodeField<'record>> DecodeField<'record> for Option<T> {
    fn decode_field(
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error> {
        match bytes {
            None | Some(b"") => Ok(None),
            Some(b) => T::decode_field(Some(b), index, name).map(Some),
        }
    }

    fn decode_field_from_record<R>(
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<Self, Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        if record.is_null_aware() {
            if record.is_field_null(index) {
                return Ok(None);
            }
            match record.get_field(index) {
                None => Ok(None),
                bytes @ Some(_) => T::decode_field(bytes, index, name).map(Some),
            }
        } else {
            Self::decode_field(record.get_field(index), index, name)
        }
    }

    fn decode_field_into(
        &mut self,
        bytes: Option<&'record [u8]>,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error> {
        match bytes {
            None | Some(b"") => {
                drop(self.take());
                Ok(())
            }
            Some(_) => decode_some_into(self, bytes, index, name),
        }
    }

    fn decode_field_into_from_record<R>(
        &mut self,
        record: &R,
        index: usize,
        name: &'static str,
    ) -> Result<(), Error>
    where
        R: DecodeRecord<'record> + ?Sized,
    {
        if !record.is_null_aware() {
            return self.decode_field_into(record.get_field(index), index, name);
        }
        if record.is_field_null(index) {
            drop(self.take());
            return Ok(());
        }
        match record.get_field(index) {
            None => {
                drop(self.take());
                Ok(())
            }
            bytes @ Some(_) => decode_some_into(self, bytes, index, name),
        }
    }
}

/// Decode a present field into `slot`, reusing the existing inner value when
/// one is already present.
fn decode_some_into<'record, T>(
    slot: &mut Option<T>,
    bytes: Option<&'record [u8]>,
    index: usize,
    name: &'static str,
) -> Result<(), Error>
where
    T: DecodeField<'record>,
{
    if let Some(inner) = slot.as_mut() {
        inner.decode_field_into(bytes, index, name)
    } else {
        *slot = Some(T::decode_field(bytes, index, name)?);
        Ok(())
    }
}

// ── EncodeField ────────────────────────────────────────────────────────────────

/// Decodes a `#[csv(default)]` field, using [`Default::default()`] when absent
/// or empty.
///
/// For a worked example, see [`super::CsvDecode`].
///
/// # Errors
///
/// Returns an [`Error`](crate::Error) when the field is present and non-empty but
/// cannot be converted to `T`.
pub fn decode_field_or_default<'record, T>(
    bytes: Option<&'record [u8]>,
    index: usize,
    name: &'static str,
) -> Result<T, Error>
where
    T: DecodeField<'record> + Default,
{
    match bytes {
        None | Some(b"") => Ok(T::default()),
        Some(b) => T::decode_field(Some(b), index, name),
    }
}

