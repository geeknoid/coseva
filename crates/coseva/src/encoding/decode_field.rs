    fn test_decode_compact_str() {
        let mut rec = ByteRecord::new();
        rec.push_field(b"bytes_field");
        rec.push_field(b"str_field");
        let r = ByteRecordRef::new(&rec);

        let mut cs = CompactString::default();
        cs.decode_field_into_from_record(&r, 1, "str_field")
            .expect("decodes compact str");
        assert_eq!(cs, "str_field");

        let mut cs_err = CompactString::default();
        assert!(
            cs_err
                .decode_field_into(Some(b"\xff\xff"), 0, "bad")
                .is_err()
        );
    }
